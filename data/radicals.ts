// Hàm tìm bộ thủ theo ID
export function getRadicalById(id: number): Radical | undefined {
  return radicals.find((r) => r.id === id);
}

// Hàm lọc bộ thủ theo số nét
export function getRadicalsByStrokes(strokes: number): Radical[] {
  return radicals.filter((r) => r.strokes === strokes);
}

import { RADICAL_HAN_VIET } from './radical-hanviet';

// Hàm tìm kiếm bộ thủ
export function searchRadicals(query: string): Radical[] {
  const q = query.toLowerCase().trim();
  if (!q) return radicals;
  return radicals.filter(
    (r) =>
      r.radical.includes(q) ||
      r.pinyin.toLowerCase().includes(q) ||
      r.meaning.toLowerCase().includes(q) ||
      (RADICAL_HAN_VIET[r.id] && RADICAL_HAN_VIET[r.id].toLowerCase().includes(q)) ||
      r.variants.some((v) => v.includes(q))
  );
}
