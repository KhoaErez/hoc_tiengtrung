/**
 * Lấy danh sách câu ca dao tục ngữ theo bộ lọc
 */
export function getProverbExercises(filter?: {
  level?: string;
  category?: string;
}): VietnameseProverbExercise[] {
  let list = VIETNAMESE_PROVERB_EXERCISES;

  if (filter?.level && filter.level !== 'all') {
    list = list.filter((item) => item.level === filter.level || item.difficulty === filter.level);
  }

  if (filter?.category && filter.category !== 'all') {
    list = list.filter((item) => item.category === filter.category);
  }

  return list;
}
